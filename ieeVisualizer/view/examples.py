"""Example views used by the gallery, the docs and the tests.

All numbers here are synthetic and labelled as such in their provenance;
none is a measurement of anything.
"""

from __future__ import annotations

from ..spec import DataSnapshot, Provenance
from .model import (
    Comparison,
    FigureComponent,
    Flow,
    FlowEdge,
    FlowLayout,
    FlowNode,
    Grid,
    Kpi,
    Note,
    Stack,
    Table,
    Text,
    ViewSpec,
)

SYNTHETIC = Provenance(source="ieeVisualizer/view/examples.py", timezone="Europe/Helsinki",
                       notes="Synthetic example values; not a measurement.")


def reporting_pipeline_flow() -> Flow:
    """The reporting pipeline of docs/CONVERSATIONAL_UI_AND_REPORTING.md section 5.2."""
    return Flow(
        title="Reporting pipeline",
        nodes=[FlowNode("agent", "Reporting agent"),
               FlowNode("evidence", "Authorized evidence", component="data"),
               FlowNode("viz", "ieeVisualizer", component="process"),
               FlowNode("email", "Email report", component="external"),
               FlowNode("web", "Interactive report", component="external")],
        edges=[FlowEdge("agent", "evidence", "queries"),
               FlowEdge("evidence", "viz", "view data"),
               FlowEdge("viz", "email", "PNG / HTML"),
               FlowEdge("viz", "web", "SVG + spec")],
        layout=FlowLayout("layered", "LR"),
        description="How an agent turns authorized evidence into report visuals.",
    )


def reporting_pipeline() -> ViewSpec:
    return ViewSpec(title="Agent reporting pipeline",
                    root=Stack([reporting_pipeline_flow(),
                                Note("Illustrative architecture, not a deployment diagram.",
                                     type="footnote")]))


def weekly_snapshot() -> DataSnapshot:
    weeks = [f"2026-{m:02d}-{d:02d}" for m, d in
             ((8, 31), (9, 7), (9, 14), (9, 21), (9, 28), (10, 5), (10, 12))]
    snap = DataSnapshot.from_columns(
        {"week": weeks, "bookings": [41, 44, None, 47, 52, 49, 55],
         "quotes": [96, 101, 88, 104, 110, None, 118]},
        units={"bookings": "count", "quotes": "count"},
        dtypes={"week": "datetime", "bookings": "int", "quotes": "int"},
        provenance=SYNTHETIC)
    snap.columns["week"].description = "Week (ISO, starting Monday)"
    for c in ("bookings", "quotes"):
        snap.columns[c].aggregation = "count per ISO week"
    return snap


def weekly_briefing() -> ViewSpec:
    """Title, three KPI tiles (one without data), a timeseries figure built
    by the ``timeseries`` template, a table with gaps and the caveats."""
    from .. import templates

    snap = weekly_snapshot()
    trend = templates.get("timeseries").build(
        snap, time_column="week", value_columns=["bookings", "quotes"],
        title="Bookings and quotes per week")
    return ViewSpec(
        title="Weekly briefing — week 42",
        figures={"trend": trend},
        datasets={"weekly": snap},
        root=Stack([
            Text("Bookings rose for the second week. **Quote data for week 41 is missing** "
                 "upstream, so conversion is not shown for that week.", style="lead"),
            Grid([
                Kpi("Bookings (week 42)", 55, unit="bookings",
                    comparison=Comparison(49, "week 41"), source="weekly snapshot",
                    dataset="weekly"),
                Kpi("Quotes (week 42)", 118, unit="quotes",
                    comparison=Comparison(None, "week 41"), source="weekly snapshot",
                    dataset="weekly"),
                Kpi("Marketing cost per booking", None, unit="EUR",
                    source="ad spend export not connected"),
            ], columns=3),
            FigureComponent(figure="trend", aspect=0.42),
            Table("weekly", title="Weekly counts"),
            Note("Week 37 bookings and week 41 quotes were not delivered by the source; "
                 "they are gaps, not zeros. Counts are synthetic example values."),
            Note("Source: synthetic weekly snapshot, Europe/Helsinki weeks starting Monday. "
                 "Generated by ieeVisualizer.view.examples.", type="footnote"),
        ]),
    )
